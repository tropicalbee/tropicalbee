import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {pixelText, textWidth} from '../../ghost-miner-kit/source/pixel-font.mjs';
import {pages, rooms, endingGuide} from './adventure.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.join(root, 'assets/adventure/ui');
const game = path.join(root, 'game');
const check = process.argv.includes('--check');
const preview = process.argv.includes('--preview');
if (check && preview) throw Error('Use --check or --preview, not both.');
const esc = value => String(value).replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;');
const slug = label => label.toLowerCase().replaceAll(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const buttons = new Map();
const frame = (width, height, body, title) => `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}" role="img"><title>${esc(title)}</title><rect width="${width}" height="${height}" fill="#1b2025"/><path d="M2 ${height - 2}V2H${width - 2}" fill="none" stroke="#52575a" stroke-width="4"/><path d="M${width - 2} 2V${height - 2}H2" fill="none" stroke="#0c0f12" stroke-width="4"/>${body}</svg>\n`;

function header(p) {
  const titleSize = Math.min(3.2, 860 / textWidth(p.title, 1));
  const status = [
    p.key ? 'KEY  BRASS' : 'KEY  NONE',
    p.cat ? 'COMPANION  CAT' : 'COMPANION  NONE',
    p.chapter === 2 ? `REPAIRS  ${p.progress} OF 5` : `SEALS  ${p.seals} OF 2`,
  ];
  return frame(960, 116,
    pixelText('TROPICALBEE - THE THIRTEENTH KNOCK', 480, 12, 1.3, '#939b9d') +
    pixelText(p.title, 480, 36, titleSize, '#d4d5cd') +
    '<path d="M2 76H958M320 76V114M640 76V114" stroke="#41474a" stroke-width="2"/>' +
    status.map((label, i) => pixelText(label, 160 + i * 320, 91, 1.6, '#b8ad93')).join(''),
    `${p.title}. ${status.join('. ')}`);
}

function button(label) {
  const id = slug(label);
  const size = Math.min(2, 244 / textWidth(label, 1));
  buttons.set(id, frame(284, 48,
    '<path d="M5 5H279V43H5Z" fill="#363b3e"/><path d="M6 42V6H278" fill="none" stroke="#606568" stroke-width="2"/><path d="M278 6V42H6" fill="none" stroke="#252a2d" stroke-width="2"/>' +
    pixelText(label, 142, (48 - size * 7) / 2, size, '#d8d9d0'), label));
  return `<img src="../assets/adventure/ui/${id}.svg" width="260" alt="${esc(label)}">`;
}

function document(p) {
  const room = rooms[p.room];
  const actions = p.choices.map(([label, target]) =>
    `  <a href="${target}.md">${button(label)}</a>`).join('\n');
  const inventory = ['Brass key', ...(p.equipment ?? []), ...(p.cat ? ['Black cat companion'] : [])];
  const journal = `<details>
<summary>House map${p.chapter === 2 ? ' and ward journal' : ''}</summary>
<p><strong>House:</strong> Foyer &rarr; Study &rarr; Attic &rarr; Garden.</p>
<p><strong>Beyond the garden:</strong> Greenhouse &rarr; Cellar &rarr; Workshop &rarr; Observatory.</p>
<p>Leave through the garden for a shorter ending, or follow the lanterns to restore the ward and free the stolen names. Backtracking preserves your inventory; Restart starts over.</p>
${p.journal ? `<ol>${p.journal.map(note => `<li>${esc(note)}</li>`).join('')}</ol>` : '<p>Find the brass key and solve the two house locks to reach the garden.</p>'}
</details>`;
  return `<!-- Generated by source/render-adventure.mjs. Edit source/adventure.mjs or source/adventure-expansion.mjs. -->
<div align="center">
<div><img src="../assets/adventure/ui/${p.id}-hud.svg" width="960" align="top" alt="${esc(p.title)}. Brass key: ${p.key ? 'carried' : 'not found'}. Companion: ${p.cat ? 'black cat' : 'none'}. ${p.chapter === 2 ? `Repairs completed: ${p.progress} of 5.` : `Seals broken: ${p.seals} of 2.`}"></div>
<div><img src="../assets/${room.file}" width="960" align="top" alt="${esc(room.alt)}"></div>
</div>

<p align="center"><strong>${esc(p.objective)}</strong></p>
${p.chapter === 2 ? `\n<p align="center"><small><strong>Inventory:</strong> ${inventory.map(esc).join(' &middot; ')}</small></p>\n` : ''}

${p.paragraphs.map(line => `<p align="center">${esc(line)}</p>`).join('\n\n')}
${actions ? `\n<p align="center">\n${actions}\n</p>\n` : ''}
${p.hint ? `<details>
<summary>Need a hint?</summary>
<p>${esc(p.hint)}</p>
</details>\n` : ''}
${journal}
<p align="center">
  <a href="start.md">Restart adventure</a>
  &nbsp;&middot;&nbsp;
  <a href="../../README.md">Return to profile</a>
${p.ending ? '  &nbsp;&middot;&nbsp;\n  <a href="endings.md">Ending collection (spoilers)</a>\n' : ''}</p>

<p align="center"><sub>Progress travels with this page. Bookmark it to resume. Restart begins a new run.</sub></p>
`;
}

const endings = `<!-- Generated by source/render-adventure.mjs. -->
# The ending collection

Six outcomes for Halloween night at Briar House. These are possible endings, not a saved achievement counter.

<details>
<summary>Reveal the endings and how to reach them</summary>

| Ending | How to find it |
| --- | --- |
${endingGuide.map(([title, how]) => `| ${title} | ${how} |`).join('\n')}

</details>

[Play again](start.md) &middot; [Return to profile](../../README.md)
`;

const files = new Map();
for (const p of pages) {
  files.set(path.join(output, `${p.id}-hud.svg`), header(p));
  files.set(path.join(game, `${p.id}.md`), document(p));
}
for (const [id, svg] of buttons) files.set(path.join(output, `${id}.svg`), svg);
files.set(path.join(game, 'endings.md'), endings);
if (!check) await fs.mkdir(output, {recursive: true});
for (const [filename, content] of files) {
  if (check) {
    const existing = (await fs.readFile(filename, 'utf8')).replaceAll('\r\n', '\n');
    if (existing !== content) throw Error(`Regenerate ${path.relative(root, filename)}`);
  } else {
    await fs.writeFile(filename, content);
  }
}
console.log(`${check ? 'Verified' : 'Rendered'} ${pages.length} game states, ${buttons.size} controls and the ending collection.`);

if (preview) {
  const previewDir = path.join(root, 'build/adventure-preview');
  await fs.mkdir(previewDir, {recursive: true});
  const wrap = (title, body) => `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(title)} - tropicalbee</title>
<style>
:root { color-scheme: dark; }
* { box-sizing: border-box; }
body { margin: 0; background: #0d1117; color: #c7c9c6; font: 16px/1.6 system-ui, sans-serif; }
main { max-width: 1012px; padding: 24px; margin: auto; }
img { max-width: 100%; height: auto; vertical-align: top; }
p { margin: 16px auto; max-width: 850px; }
a { color: #b8ad93; }
a:focus-visible { outline: 3px solid #d4d5cd; outline-offset: 4px; }
p > a > img { margin-bottom: 4px; }
div > img { margin: 0; }
details { max-width: 850px; margin: 20px auto; padding: 12px; border: 1px solid #41474a; }
summary { cursor: pointer; }
sub { font-size: 12px; color: #939b9d; }
@media (max-width: 600px) { main { padding: 12px; } }
</style></head><body><main>${body}</main></body></html>\n`;
  const local = body => body
    .replaceAll('../assets/', '../../assets/')
    .replaceAll('../../README.md', '../../../preview.html')
    .replaceAll(/href="([a-z-]+)\.md"/g, 'href="$1.html"');
  for (const p of pages) {
    await fs.writeFile(path.join(previewDir, `${p.id}.html`), wrap(p.title, local(document(p))));
  }
  await fs.writeFile(path.join(previewDir, 'endings.html'), wrap('The ending collection',
    '<h1>The ending collection</h1><p>Six possible endings. This is not a saved achievement counter.</p>' +
    '<details><summary>Reveal the endings</summary>' +
    endingGuide.map(([title, how]) => `<p><strong>${esc(title)}</strong><br>${esc(how)}</p>`).join('') +
    '</details><p><a href="start.html">Play again</a> &middot; <a href="../../../preview.html">Return to profile</a></p>'));
  const profilePreview = path.join(root, '../preview.html');
  const profile = await fs.readFile(path.join(root, '../README.md'), 'utf8');
  const localProfile = profile.replaceAll('tropicalbee-halloween-banner-kit/game/start.md',
    'tropicalbee-halloween-banner-kit/build/adventure-preview/start.html');
  await fs.writeFile(profilePreview, wrap('Profile preview', localProfile));
  console.log('Local preview: preview.html (banner opens the playable HTML adventure preview).');
}
